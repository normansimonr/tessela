#!/usr/bin/env python3
"""
Stage 2: Populate database with normalized data and generate reports.

This script:
1. Reads the mapping CSVs generated by merge.py
2. Inserts normalized JSON into the database
3. Generates comprehensive consistency reports
"""

import sqlite3
import csv
import json
import sys
from pathlib import Path
from collections import defaultdict
from typing import Dict, List, Tuple

def load_mapping_csv(csv_path: str) -> List[Dict]:
    """Load a mapping CSV."""
    rows = []
    with open(csv_path, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            rows.append(row)
    return rows

def populate_tradition(db_path: str, tradition: str, mapping_rows: List[Dict], 
                      csv_path: str, norm_column: str, db_table: str) -> Dict:
    """
    Populate normalization column for a tradition.
    
    Returns:
        Stats dict with counts
    """
    db = sqlite3.connect(db_path)
    cur = db.cursor()
    
    # Build a map from CSV coordinates to normalization JSON
    csv_norms = {}
    with open(csv_path, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Strip .0 from verse numbers for LXX
            verse = row['verse'].rstrip('0').rstrip('.') if row['verse'].endswith('.0') else row['verse']
            key = (row['book_name'], row['chapter'], verse)
            csv_norms[key] = row['normalization']
    
    # Process matches
    inserted = 0
    skipped = 0
    errors = 0
    
    for mapping in mapping_rows:
        if mapping['match_status'] != 'matched':
            skipped += 1
            continue
        
        verse_id = mapping['db_verse_id']
        if not verse_id:
            skipped += 1
            continue
        
        # Get the normalization JSON
        key = (mapping['csv_book_name'], mapping['csv_chapter'], mapping['csv_verse'])
        norm_json = csv_norms.get(key)
        
        if not norm_json:
            errors += 1
            continue
        
        # Validate that it's valid JSON
        try:
            parsed = json.loads(norm_json)
            if not isinstance(parsed, list):
                errors += 1
                continue
        except json.JSONDecodeError:
            errors += 1
            continue
        
        # Update database
        try:
            cur.execute(
                f"UPDATE {db_table} SET {norm_column} = ? WHERE verseID = ?",
                (norm_json, verse_id)
            )
            inserted += 1
        except Exception as e:
            print(f"Error updating {verse_id}: {e}", file=sys.stderr)
            errors += 1
    
    db.commit()
    db.close()
    
    return {
        'inserted': inserted,
        'skipped': skipped,
        'errors': errors
    }

def generate_coverage_report(db_path: str) -> str:
    """Generate coverage statistics."""
    db = sqlite3.connect(db_path)
    cur = db.cursor()
    
    report = []
    report.append("# Coverage Statistics\n")
    
    for norm_col, table in [
        ('mt_norm', 'raw_masoretic'),
        ('lxx_norm', 'raw_septuagint'),
        ('vulgate_norm', 'raw_vulgate'),
    ]:
        # Count total and normalized
        cur.execute(f"SELECT COUNT(*) as total FROM {table}")
        total = cur.fetchone()[0]
        
        cur.execute(f"SELECT COUNT(*) as with_norm FROM {table} WHERE {norm_col} IS NOT NULL")
        with_norm = cur.fetchone()[0]
        
        pct = (with_norm / total * 100) if total > 0 else 0
        report.append(f"- **{norm_col}**: {with_norm}/{total} ({pct:.1f}%)")
    
    db.close()
    return "\n".join(report)

def generate_lxx_tov_analysis(db_path: str, mapping_rows: List[Dict]) -> str:
    """Generate LXX Tov cross-check analysis."""
    db = sqlite3.connect(db_path)
    db.row_factory = sqlite3.Row
    cur = db.cursor()
    
    report = []
    report.append("# LXX Tov Alignment Analysis\n")
    
    # Get all Tov verses
    cur.execute("SELECT * FROM raw_tov_distilled")
    tov_verses = {(row['book'], row['chapter'], row['verse']) for row in cur.fetchall()}
    
    # Get all normalized LXX verses from mapping
    normalized_lxx = set()
    for mapping in mapping_rows:
        if mapping['match_status'] == 'matched':
            key = (mapping['db_book'], mapping['csv_chapter'], mapping['csv_verse'])
            normalized_lxx.add(key)
    
    # Check alignment
    tov_normalized = normalized_lxx & tov_verses
    tov_not_normalized = tov_verses - normalized_lxx
    normalized_not_tov = normalized_lxx - tov_verses
    
    report.append(f"- **Total Tov verses**: {len(tov_verses)}")
    report.append(f"- **Tov verses normalized**: {len(tov_normalized)} ({len(tov_normalized)/len(tov_verses)*100:.1f}%)")
    report.append(f"- **Tov verses NOT normalized**: {len(tov_not_normalized)}")
    report.append(f"- **Normalized verses NOT in Tov**: {len(normalized_not_tov)}")
    report.append("")
    
    if len(tov_not_normalized) > 0:
        report.append("⚠️ **Tov verses that were NOT normalized** (sample):")
        for key in sorted(list(tov_not_normalized)[:10]):
            report.append(f"  - {key[0]} {key[1]}:{key[2]}")
    
    if len(normalized_not_tov) > 0:
        report.append("\n⚠️ **Normalized verses NOT in Tov** (potential Tov coordinate errors):")
        for key in sorted(list(normalized_not_tov)[:10]):
            report.append(f"  - {key[0]} {key[1]}:{key[2]}")
    
    db.close()
    return "\n".join(report)

def generate_vulgate_validation(db_path: str, mapping_rows: List[Dict]) -> str:
    """Generate Vulgate text validation summary."""
    report = []
    report.append("# Vulgate Text Validation\n")
    
    # Count matches vs mismatches
    matched = sum(1 for m in mapping_rows if m['match_status'] == 'matched')
    text_mismatch = sum(1 for m in mapping_rows if m['match_status'] == 'text_mismatch')
    unmatched = sum(1 for m in mapping_rows if m['match_status'] == 'unmatched')
    total = len(mapping_rows)
    
    report.append(f"- **Total Vulgate verses in CSV**: {total}")
    report.append(f"- **Matched with DB text**: {matched} ({matched/total*100:.1f}%)")
    report.append(f"- **Text mismatches after lenient normalization**: {text_mismatch} ({text_mismatch/total*100:.1f}%)")
    report.append(f"- **Unmatched coordinates**: {unmatched}")
    report.append("")
    
    if text_mismatch == 0:
        report.append("✅ **All Vulgate base texts match perfectly!**")
    elif text_mismatch < total * 0.05:
        report.append("✅ **Vulgate text validation PASSED** - <5% mismatches (acceptable)")
    else:
        report.append("⚠️ **Vulgate text validation**: Some texts differ significantly")
        report.append("  (May indicate OCR differences or different source text version)")
    
    return "\n".join(report)

def generate_mismatch_details(mapping_rows: List[Dict], tradition: str) -> str:
    """Generate mismatch details."""
    report = []
    report.append(f"# {tradition.upper()} Mismatch Details\n")
    
    unmatched = [m for m in mapping_rows if m['match_status'] == 'unmatched']
    text_mismatches = [m for m in mapping_rows if m['match_status'] == 'text_mismatch']
    
    report.append(f"- **Unmatched verses (coordinates not found)**: {len(unmatched)}")
    report.append(f"- **Text mismatches (after lenient normalization)**: {len(text_mismatches)}")
    report.append("")
    
    if len(unmatched) > 0:
        report.append(f"**Sample unmatched verses** (first 20):")
        for m in unmatched[:20]:
            report.append(f"  - {m['csv_book_name']} {m['csv_chapter']}:{m['csv_verse']}")
    
    return "\n".join(report)

